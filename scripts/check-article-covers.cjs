'use strict';

// Run explicitly after all eight real images are delivered and the site is built.
// Hexo imports scripts/ during generation: no checks or I/O outside this CLI guard.
function checkArticleCovers() {
  const assert = require('node:assert/strict');
  const fs = require('node:fs');
  const path = require('node:path');
  const {execFileSync} = require('node:child_process');
  const {createHash} = require('node:crypto');
  const yaml = require('js-yaml'); // Already used by check-site.cjs; no new package.
  const root = path.resolve(__dirname, '..');
  const baseline = '9d5dea61f4a9012922817e39d555a2e7ee790d89';
  const prefix = '/img/covers/notebook/20261105/';
  const articles = [
    ['AI使用感受.md', 'ai-feedback-loop'],
    ['智能车项目经验与比赛流程.md', 'robot-growth'],
    ['睿抗赛94分复盘.md', 'ruikang-route-review'],
    ['睿抗赛四套视觉方案.md', 'ruikang-vision-studies'],
    ['智慧药房机器人比赛参赛复盘.md', 'pharmacy-dual-robots'],
    ['国三之后我把智慧药房比赛做成了一套工作流.md', 'pharmacy-workflow'],
    ['YOLOv5模型训练.md', 'yolov5-pollination'],
    ['ISCC微型工厂模拟赛道经验分享.md', 'iscc-secure-factory']
  ];
  const photo = '/img/covers/ruikang-national-first.jpg';
  const photoSha = 'ea4ddecc8155c479504be99edb254102094d69eadb4c8abd92fc7685e48c250f';
  const config = yaml.load(fs.readFileSync(path.join(root, '_config.yml'), 'utf8'));
  assert.equal(config.permalink, ':year/:month/:day/:title/', 'Checker expects the current permalink contract');
  const sha = bytes => createHash('sha256').update(bytes).digest('hex');
  const attrs = tag => Object.fromEntries([...tag.matchAll(/([\w:-]+)\s*=\s*(["'])(.*?)\2/g)]
    .map(match => [match[1], match[3].replaceAll('&quot;', '"').replaceAll('&#39;', "'").replaceAll('&amp;', '&')]));
  const tags = (html, name) => [...html.matchAll(new RegExp(`<${name}\\b[^>]*>`, 'gi'))].map(match => attrs(match[0]));
  const hasClass = (attributes, name) => (attributes.class || '').split(/\s+/).includes(name);
  function frontMatter(text, label) {
    const match = text.match(/^---\r?\n([\s\S]*?)\r?\n---(?:\r?\n|$)/);
    assert.ok(match, `${label}: missing front matter`);
    return match[1];
  }
  function readAsset(directory, url) {
    const file = path.join(root, directory, url);
    assert.ok(fs.existsSync(file), `${file}: missing; deliver all images and build before running this checker`);
    assert.ok(fs.statSync(file).isFile(), `${file}: expected a regular image file`);
    const bytes = fs.readFileSync(file);
    assert.ok(bytes.length > 0, `${file}: empty image`);
    return bytes;
  }
  for (const [filename, slug] of [...articles, ['睿抗：从初赛到国一.md', null]]) {
    const concept = slug !== null;
    const cover = concept ? `${prefix}${slug}.webp` : photo;
    const relative = `source/_posts/${filename}`;
    const original = execFileSync('git', ['show', `${baseline}:${relative}`], {cwd: root});
    const current = fs.readFileSync(path.join(root, relative));
    let expected = original;
    if (concept) {
      const originalText = original.toString('utf8');
      const coverLines = frontMatter(originalText, filename).match(/^cover:[^\r\n]*/gm) || [];
      assert.equal(coverLines.length, 1, `${filename}: baseline must have exactly one cover line`);
      expected = Buffer.from(originalText.replace(coverLines[0], `cover: ${cover}`), 'utf8');
    }
    assert.deepEqual(current, expected, concept
      ? `${filename}: only the cover line may differ from ${baseline}`
      : `${filename}: protected article must remain byte-identical to ${baseline}`);
    const front = frontMatter(current.toString('utf8'), filename);
    assert.equal(yaml.load(front).cover, cover, `${filename}: wrong source cover`);

    const source = readAsset('source', cover);
    const generated = readAsset('public', cover);
    assert.equal(sha(generated), sha(source), `${cover}: generated bytes must match the source`);
    if (concept) {
      const probe = JSON.parse(execFileSync('ffprobe', [
        '-v', 'error', '-select_streams', 'v:0', '-show_entries', 'stream=codec_name,width,height',
        '-of', 'json', path.join(root, 'source', cover)
      ], {encoding: 'utf8'}));
      assert.equal(probe.streams.length, 1, `${cover}: expected one image stream`);
      assert.deepEqual(probe.streams[0], {codec_name: 'webp', width: 1536, height: 864},
        `${cover}: expected an actual 1536×864 WebP image`);
    } else {
      assert.equal(sha(source), photoSha, 'Protected group photo SHA-256 changed');
    }

    const date = front.match(/^date: (\d{4})-(\d{2})-(\d{2})/m);
    assert.ok(date, `${filename}: missing date for the current permalink`);
    const route = `${date.slice(1).join('/')}/${path.basename(filename, '.md')}/index.html`;
    const html = fs.readFileSync(path.join(root, 'public', route), 'utf8');
    const images = tags(html, 'meta').filter(meta => meta.property === 'og:image');
    assert.equal(images.length, 1, `${filename}: expected exactly one og:image`);
    assert.equal(images[0].content, new URL(cover, config.url).href, `${filename}: wrong og:image`);
    const heading = html.match(/<header\b[^>]*class="article-heading"[^>]*>([\s\S]*?)<\/header>/)?.[1];
    assert.ok(heading, `${filename}: missing generated article heading`);
    const covers = tags(heading, 'img').filter(image => hasClass(image, 'article-cover'));
    assert.equal(covers.length, 1, `${filename}: expected one article cover`);
    assert.equal(covers[0].src, cover, `${filename}: wrong generated cover reference`);
    assert.equal((covers[0].alt || '').includes('AI 概念插画'), concept, `${filename}: wrong concept-image alt text`);
    const credits = tags(heading, 'span').filter(span => hasClass(span, 'cover-credit'));
    assert.equal(credits.length, concept ? 1 : 0, `${filename}: wrong concept declaration count`);
    assert.equal(heading.includes('封面为 AI 概念插画，用于主题表达'), concept, `${filename}: wrong concept declaration`);
  }
  console.log('Article cover checks passed: 8 independent 1536×864 WebP covers, source/generated bytes and article references, og:image and concept declarations; only cover lines changed from 9d5dea6; protected article and group photo unchanged.');
}

if (require.main === module) checkArticleCovers();
