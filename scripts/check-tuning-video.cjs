'use strict';

// Run after a clean build, once the actual MP4 and VTT have been delivered.
// Hexo imports scripts/ during generation; keep all assertions CLI-only.
function checkTuningVideo() {
  const assert = require('node:assert/strict');
  const fs = require('node:fs');
  const path = require('node:path');
  const {execFileSync} = require('node:child_process');
  const {createHash} = require('node:crypto');
  const {TextDecoder} = require('node:util');
  const root = path.resolve(__dirname, '..');
  const media = '/media/tuning-workshop.mp4';
  const subtitles = '/media/tuning-workshop.zh-CN.vtt';
  const buffers = new Map();
  for (const url of [media, subtitles]) {
    const source = path.join(root, 'source', url);
    const generated = path.join(root, 'public', url);
    assert.ok(fs.existsSync(source), `Missing real source asset: ${source}`);
    assert.ok(fs.existsSync(generated), `Missing generated asset: ${generated}; build after media delivery`);
    assert.ok(fs.statSync(source).isFile() && fs.statSync(generated).isFile(), `${url}: expected regular files`);
    assert.ok(fs.statSync(source).size > 0 && fs.statSync(source).size < 20_000_000, `${url}: must be nonempty and below 20 MB`);
    const bytes = fs.readFileSync(source);
    const digest = data => createHash('sha256').update(data).digest('hex');
    assert.equal(digest(bytes), digest(fs.readFileSync(generated)), `${url}: generated bytes differ from source`);
    buffers.set(url, bytes);
  }

  const html = fs.readFileSync(path.join(root, 'public/index.html'), 'utf8');
  const videos = [...html.matchAll(/<video\b[^>]*>([\s\S]*?)<\/video>/gi)];
  assert.equal(videos.length, 1, 'Generated homepage must contain exactly one native video');
  const attrs = tag => Object.fromEntries([...tag.matchAll(/([\w:-]+)(?:\s*=\s*(?:"([^"]*)"|'([^']*)'|([^\s>]+)))?/g)]
    .map(match => [match[1].toLowerCase(), match[2] ?? match[3] ?? match[4] ?? '']));
  const tags = name => [...videos[0][1].matchAll(new RegExp(`<${name}\\b[^>]*>`, 'gi'))].map(match => attrs(match[0]));
  const videoAttributes = attrs(videos[0][0].match(/^<video\b[^>]*>/i)[0]);
  assert.equal(videoAttributes.poster, '/img/workshop/tuning-film-poster.webp', 'Use the actual film-frame poster, not the desktop illustration');
  const sources = tags('source');
  const tracks = tags('track');
  assert.equal(sources.length, 1, 'Expected one native video source');
  assert.equal(sources[0].src, media);
  assert.equal(sources[0].type, 'video/mp4');
  assert.equal(tracks.length, 1, 'Expected one Chinese captions track');
  assert.equal(tracks[0].src, subtitles);
  assert.equal(tracks[0].kind, 'captions');
  assert.equal(tracks[0].srclang, 'zh-CN');
  assert.equal(tracks[0].label, '声音说明', 'Optional captions describe non-dialogue sounds');
  assert.ok(!('default' in tracks[0]), 'Keep sound descriptions off by default so they do not cover the dialogue-free picture');

  const probe = JSON.parse(execFileSync('ffprobe', [
    '-v', 'error', '-show_format', '-show_streams', '-of', 'json', path.join(root, 'source', media)
  ], {encoding: 'utf8'}));
  const duration = Number(probe.format.duration);
  assert.ok(duration > 60 && Math.abs(duration - 75) <= 1, `Expected about 75 seconds (74–76), got ${duration}`);
  const videoStreams = probe.streams.filter(stream => stream.codec_type === 'video');
  const audioStreams = probe.streams.filter(stream => stream.codec_type === 'audio');
  assert.equal(videoStreams.length, 1, 'Expected exactly one video stream');
  assert.equal(audioStreams.length, 1, 'Expected exactly one audio stream');
  const video = videoStreams[0];
  assert.equal(video.codec_name, 'h264');
  assert.equal(video.pix_fmt, 'yuv420p', 'Require browser-compatible H.264 4:2:0');
  assert.equal(video.width, 1280);
  assert.equal(video.height, 720);
  const rate = value => { const [n, d] = value.split('/').map(Number); return n / d; };
  assert.equal(rate(video.r_frame_rate), 24, 'Expected 24 fps');
  assert.ok(Math.abs(rate(video.avg_frame_rate) - 24) < 0.01, 'Expected average 24 fps');
  assert.equal(audioStreams[0].codec_name, 'aac');

  // Read top-level ISO BMFF boxes, not incidental "moov" text inside payloads.
  const mp4 = buffers.get(media);
  const boxes = [];
  for (let offset = 0; offset < mp4.length;) {
    assert.ok(offset + 8 <= mp4.length, 'Truncated MP4 box header');
    let size = mp4.readUInt32BE(offset);
    let header = 8;
    if (size === 1) {
      assert.ok(offset + 16 <= mp4.length, 'Truncated extended MP4 box header');
      size = Number(mp4.readBigUInt64BE(offset + 8));
      header = 16;
    } else if (size === 0) size = mp4.length - offset;
    assert.ok(Number.isSafeInteger(size) && size >= header && offset + size <= mp4.length, 'Invalid MP4 box size');
    boxes.push(mp4.toString('ascii', offset + 4, offset + 8));
    offset += size;
  }
  assert.ok(boxes.includes('ftyp') && boxes.includes('moov') && boxes.includes('mdat'), 'Expected a complete MP4 container');
  assert.ok(boxes.indexOf('moov') < boxes.indexOf('mdat'), 'MP4 must use faststart: moov before mdat');

  const vtt = new TextDecoder('utf-8', {fatal: true}).decode(buffers.get(subtitles)).replace(/\r\n?/g, '\n');
  assert.ok(!vtt.includes('\0'), 'VTT must not contain NUL');
  assert.ok(!/接头|开关|插头|插座|插电|插接|插拔|接线|接电|手按|按下|伸手|手动启动/.test(vtt), 'Autonomous-start film must not describe connector, switch, plugging-in or manual-start actions');
  assert.ok(!/小胖子调车|一段原创黏土概念动画|先把路线想清楚|敲几行|画几笔|小车[，,]你准备好了吗|怎么一点动静都没有|先别急着重写|挨个检查|先看电|再看代码|插头还在这儿呢|改一点[，,]跑一圈|不是只盯屏幕|也要看看车怎么走|路锥挡在前面|把路线让开一点|绕过去|记下这次改了什么|慢慢转回来|回到熟悉的起点|平平安安回来啦|调车没有魔法|只有一轮又一轮|供电小插曲|原创借梗|不是比赛故障复现/.test(vtt), 'VTT must not retain the old title, dialogue or explanatory narrative');
  const blocks = vtt.trimEnd().split(/\n(?:[\t ]*\n)+/);
  assert.match(blocks.shift(), /^WEBVTT(?:[\t ][^\n]*)?$/, 'Expected WEBVTT header and a blank line');
  const timestamp = '(?:\\d{2,}:)?[0-5]\\d:[0-5]\\d\\.\\d{3}';
  const timing = new RegExp(`^(${timestamp})[\\t ]+-->[\\t ]+(${timestamp})(?:[\\t ]+[^\\n]+)?$`);
  const seconds = value => value.split(':').reduce((total, part) => total * 60 + Number(part), 0);
  let cues = 0, previousStart = -1;
  for (const block of blocks) {
    if (/^NOTE(?:[\t ]|\n|$)/.test(block)) continue;
    const lines = block.split('\n');
    if (!lines[0].includes('-->')) lines.shift();
    const match = timing.exec(lines.shift() || '');
    assert.ok(match, `Invalid VTT cue timing in block: ${block.slice(0, 100)}`);
    const start = seconds(match[1]), end = seconds(match[2]);
    assert.ok(start >= previousStart && end > start && end <= duration + 0.25, `Invalid or out-of-range VTT interval: ${match[0]}`);
    const description = lines.join('\n').trim();
    assert.ok(description && !lines.some(line => line.includes('-->')), 'VTT cue must contain valid nonempty text');
    assert.ok(/音乐|乐声|琴声|鼓点|拨弦|敲击|敲键|键盘|电机|马达|履带|轮胎|轮子|脚步|咔哒|咔嗒|咔嚓|提示音|提示声|电流|嗡鸣|嗡声|嗡嗡|蜂鸣|转动声|滚动声|摩擦声|机械声|环境音|环境声|底噪|叮|嘀|滴|啪|碰撞声|轻响|沙沙声/.test(description), `VTT must describe an actual non-dialogue sound, not story narration: ${description}`);
    previousStart = start;
    cues++;
  }
  assert.ok(cues >= 5 && cues <= 8, `Expected 5–8 optional sound-description cues, got ${cues}`);
  console.log(`Tuning video contract passed: ${duration.toFixed(2)}s, 1280×720 / 24fps H.264 yuv420p + AAC, ${(mp4.length / 1_000_000).toFixed(2)} MB, faststart, ${cues} optional non-dialogue sound cues, exact generated assets and native source/track.`);
}

if (require.main === module) checkTuningVideo();
